/*
 * Custom - HuffmanCompress
 *
 * Huffman-compresses src into dst using huffmanEncoding[]: pack each
 * byte's code MSB-first, append the 4-bit flush marker, and pad to
 * a byte boundary. UoDemo.exe shipped no encoder; the table and the
 * client's decode tree drive the format.
 */
int
HuffmanCompress(uint8_t *dst, uint8_t *src, int len)
{
	int i, entry;
	int bitCount = 0;
	int bitValue = 0;
	int outLen = 0;

	for (i = 0; i < len; i++) {
		entry = src[i] * 2;

		bitCount += huffmanEncoding[entry];
		bitValue <<= huffmanEncoding[entry];
		bitValue |= huffmanEncoding[entry + 1];

		while (bitCount >= 8) {
			bitCount -= 8;
			dst[outLen++] = (bitValue >> bitCount) & 0xFF;
		}
	}

	entry = 256 * 2;
	bitCount += huffmanEncoding[entry];
	bitValue <<= huffmanEncoding[entry];
	bitValue |= huffmanEncoding[entry + 1];

	if (bitCount & 7) {
		bitValue <<= 8 - (bitCount & 7);
		bitCount += 8 - (bitCount & 7);
	}

	while (bitCount >= 8) {
		bitCount -= 8;
		dst[outLen++] = (bitValue >> bitCount) & 0xFF;
	}

	return outLen;
}
